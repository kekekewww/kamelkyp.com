/**
 * Where a retired admin URL lands in the Studio (admin-architecture §2.3,
 * wp5 §4.4–§4.5). Pure: no server import, so node unit tests load it.
 *
 * React Router matches routes case-insensitively (`/ADMIN/Works` reaches the
 * `admin/works` route), so every pattern carries the `i` flag; otherwise a
 * mixed-case bookmark would fall through to the Studio home.
 */

const COMMISSIONS = "/studio/commissions";

/** Static legacy paths → Studio path (first match wins). */
const STATIC_LEGACY_TARGETS: ReadonlyArray<readonly [RegExp, string]> = [
  [/^\/admin\/?$/i, "/studio"],
  [/^\/admin\/content\/?$/i, "/studio"],
  [/^\/admin\/works\/?$/i, "/studio/projects"],
  [/^\/admin\/posts\/?$/i, "/studio/writing"],
  [/^\/admin\/services\/?$/i, "/studio/services/pricing"],
  [/^\/admin\/terms\/?$/i, "/studio/services/terms"],
  [/^\/admin\/links\/?$/i, "/studio/settings/footer"],
  [
    /^\/admin\/cases(?:\/(?:status|student-discount|cleanup))?\/?$/i,
    COMMISSIONS,
  ],
];

/** The three legacy editor/preview paths that carry a content version id. */
const VERSION_PATH =
  /^\/admin\/(?:content\/([^/]+)\/(?:edit|preview)|posts\/([^/]+)\/edit)\/?$/i;

/** Longer ids were never generated by the legacy editor. */
const MAX_LEGACY_VERSION_ID_LENGTH = 128;

/**
 * Studio path of a static legacy URL, or null when the path is not one.
 * The case list forwards its query (`service`, `status`, `cursor`): the
 * Studio inbox reads the same names (wp1 `parseCommissionQuery`).
 */
export function staticLegacyAdminTarget(url: URL): string | null {
  for (const [pattern, target] of STATIC_LEGACY_TARGETS) {
    if (pattern.test(url.pathname)) {
      return target === COMMISSIONS ? `${target}${url.search}` : target;
    }
  }
  return null;
}

/**
 * The version id of a legacy editor or preview path: `undefined` when the
 * path is not one, `null` when the id cannot be decoded or is overlong.
 */
export function legacyVersionId(pathname: string): string | null | undefined {
  const match = VERSION_PATH.exec(pathname);
  if (!match) return undefined;
  try {
    const id = decodeURIComponent(match[1] ?? match[2] ?? "");
    return id.length > MAX_LEGACY_VERSION_ID_LENGTH ? null : id;
  } catch {
    return null;
  }
}

/** One legacy entry and the Studio rows imported from it (`legacy_source`). */
export type LegacyEntryRow = {
  kind: string;
  slug: string;
  project_id: string | null;
  writing_id: string | null;
};

/**
 * Studio path for a legacy content entry: its imported project or writing,
 * else that list; the home page → Homepage; anything else → the Studio home
 * (pages other than home are retired, content-schema §3.3).
 */
export function legacyEntryTarget(row: LegacyEntryRow | null): string {
  if (row?.kind === "work") {
    return row.project_id
      ? `/studio/projects/${encodeURIComponent(row.project_id)}`
      : "/studio/projects";
  }
  if (row?.kind === "post") {
    return row.writing_id
      ? `/studio/writing/${encodeURIComponent(row.writing_id)}`
      : "/studio/writing";
  }
  if (row?.kind === "page" && row.slug === "home") return "/studio/homepage";
  return "/studio";
}
